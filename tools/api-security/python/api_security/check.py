"""The enforced-level check, SPEC-034 REQ-012 and REQ-015.

    python3 -m security.api_security.check [--root DIR] [--update-snapshot]

Reads `security/config.json`, imports the project's roles and handler modules, and fails when:
a handler carries no declaration; a role route whose path carries a parameter says neither
`owns` nor `unowned`; a deployed route has no declared handler; a declared handler has
no deployed route; the public routes differ from `security/public-routes.txt`; or, when
config.json says `"hardened": true`, a third-party action in the security or deploy workflows is
not pinned to a full commit SHA.

Exit 0 pass, 1 a finding, 2 the check itself could not run. 2 is a failure too: the check fails
closed, so an error is never a pass.
"""
import argparse
import importlib
import json
import re
import sys
from pathlib import Path
from typing import List, Set, Tuple

from . import pins, registry
from .markers import SEMGREP_SKIPS
from .adapters import AdapterError, dispatch, terraform_apigw

SNAPSHOT = Path("security") / "public-routes.txt"
CONFIG = Path("security") / "config.json"


def load_config(root: Path) -> dict:
    path = root / CONFIG
    if not path.is_file():
        raise RuntimeError(f"{CONFIG} not found under {root}")
    config = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict) or not config.get("handler_modules") or not config.get("adapter"):
        raise RuntimeError(f"{CONFIG} needs handler_modules and adapter")
    return config


def deployed(root: Path, adapter: dict) -> Set[Tuple[str, str]]:
    kind = adapter.get("kind")
    if kind == "terraform":
        return terraform_apigw.deployed_routes(root, adapter.get("paths") or [])
    if kind == "dispatch":
        return dispatch.deployed_routes(adapter.get("table") or "")
    raise AdapterError(f"unknown adapter kind {kind!r}; use 'terraform' or 'dispatch'")


def read_snapshot(root: Path) -> Set[str]:
    path = root / SNAPSHOT
    if not path.is_file():
        raise RuntimeError(f"{SNAPSHOT} not found; create it (empty is fine) with --update-snapshot")
    lines = (line.strip() for line in path.read_text(encoding="utf-8").splitlines())
    return {line for line in lines if line and not line.startswith("#")}

PARAM = re.compile(r"\{([^}+]+)\+?\}")  # {name} and greedy {name+}


def write_snapshot(root: Path, public: Set[str]) -> None:
    header = ("# Public routes, generated by `python3 -m security.api_security.check --update-snapshot`.\n"
              "# Adding a line needs a commit signed by a key in the base branch's security/allowed_signers.\n")
    (root / SNAPSHOT).write_text(header + "".join(f"{r}\n" for r in sorted(public)), encoding="utf-8")


def run(root: Path, update_snapshot: bool) -> Tuple[int, List[str]]:
    config = load_config(root)
    sys.path.insert(0, str(root))
    if config.get("roles_module"):
        importlib.import_module(config["roles_module"])
    for name in config["handler_modules"]:
        importlib.import_module(name)

    findings: List[str] = []
    for ignore in sorted(root.rglob(".semgrepignore")):  # semgrep honours one in any folder
        if ".git" not in ignore.relative_to(root).parts:
            findings.append(f"{ignore.relative_to(root).as_posix()}: an ignore file can hide handlers from "
                            "the identity scan; remove it, and exclude test data with a reasoned nosemgrep "
                            "marker instead")
    for name in config["handler_modules"]:
        where = Path(getattr(sys.modules[name], "__file__", "") or "").resolve()
        rel = where.relative_to(root.resolve()) if where.is_relative_to(root.resolve()) else where
        if SEMGREP_SKIPS.intersection(rel.parts[:-1]):
            findings.append(f"{rel.as_posix()}: semgrep skips this folder by default, so the identity scan "
                            "never reads this handler module; move it")
    routes = registry.routes()
    for r in routes:
        if r.policy is None:
            findings.append(f"{r.method} {r.path}: handler {r.handler} has no declaration; add public(reason=...) or role(...)")

        elif r.policy.kind == "role" and not r.policy.owns and not r.policy.unowned:
            params = PARAM.findall(r.path)
            if params:
                findings.append(
                    f"{r.method} {r.path}: role route with path parameter(s) {', '.join(params)} and no "
                    f"owns; add owns='{params[0]}', or unowned='<why any holder of the role may reach "
                    "every value>'")

    declared = {(r.method, r.path) for r in routes}
    live = deployed(root, config["adapter"])
    for method, path in sorted(live - declared):
        greedy = method == "ANY" or "+}" in path
        findings.append(f"{method} {path}: deployed with no declared handler; declare it, or remove the route"
                        + ("; a greedy route hands every path to one function, which the dispatch adapter "
                           "reads (api-security.md, Choosing an adapter)" if greedy else ""))
    for method, path in sorted(declared - live):
        findings.append(f"{method} {path}: declared with no deployed route; remove the handler, or deploy the route")

    if config.get("hardened"):
        workflows = list(pins.SECURITY_WORKFLOWS) + list(config.get("deploy_workflows") or [])
        findings.extend(pins.unpinned(root, workflows))

    public = {f"{r.method} {r.path}" for r in routes if r.policy is not None and r.policy.kind == "public"}
    if update_snapshot:
        write_snapshot(root, public)
    else:
        recorded = read_snapshot(root)
        if public != recorded:
            diff = [f"+ {x}" for x in sorted(public - recorded)] + [f"- {x}" for x in sorted(recorded - public)]
            findings.append("public routes differ from security/public-routes.txt "
                            "(run with --update-snapshot, and sign the commit if a line was added):\n  "
                            + "\n  ".join(diff))
    return (1 if findings else 0), findings


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="api_security.check")
    ap.add_argument("--root", default=".")
    ap.add_argument("--update-snapshot", action="store_true")
    args = ap.parse_args(argv)
    try:
        code, findings = run(Path(args.root).resolve(), args.update_snapshot)
    except Exception as exc:  # fail closed: an error in the check is a failure, never a pass
        print(f"api-security check could not run: {type(exc).__name__}: {exc}")
        return 2
    for f in findings:
        print(f"FAIL {f}")
    print("api-security check: " + ("passed" if code == 0 else f"{len(findings)} finding(s)"))
    return code


if __name__ == "__main__":
    sys.exit(main())
